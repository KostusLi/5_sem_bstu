CREATE OR REPLACE TRIGGER TRG_BEFORE_STMT
BEFORE INSERT OR DELETE OR UPDATE ON LAB12_T1
DECLARE
    v_op VARCHAR2(20);
BEGIN
    DBMS_OUTPUT.PUT_LINE('TRG_BEFORE_STMT');
    IF INSERTING THEN v_op := 'INSERT';
    ELSIF UPDATING THEN v_op := 'UPDATE';
    ELSIF DELETING THEN v_op := 'DELETE';
    END IF;
    INSERT INTO "AUDIT" VALUES (SYSDATE, v_op, 'TRG_BEFORE_STMT', 'Statement level');
END;
/

CREATE OR REPLACE TRIGGER TRG_BEFORE_ROW
BEFORE INSERT OR DELETE OR UPDATE ON LAB12_T1
FOR EACH ROW
DECLARE
    v_op VARCHAR2(20);
    v_data VARCHAR2(500);
BEGIN
    IF INSERTING THEN
        DBMS_OUTPUT.PUT_LINE('TRG_BEFORE_ROW (INSERTING)');
        v_op := 'INSERT';
        v_data := 'NEW: ' || :NEW.ID || ', ' || :NEW.NAME || ', ' || :NEW.VALUE;
    ELSIF UPDATING THEN
        DBMS_OUTPUT.PUT_LINE('TRG_BEFORE_ROW (UPDATING)');
        v_op := 'UPDATE';
        v_data := 'OLD: ' || :OLD.ID || ',' || :OLD.NAME || ',' || :OLD.VALUE ||
                  ' -> NEW: ' || :NEW.ID || ',' || :NEW.NAME || ',' || :NEW.VALUE;
    ELSIF DELETING THEN
        DBMS_OUTPUT.PUT_LINE('TRG_BEFORE_ROW (DELETING)');
        v_op := 'DELETE';
        v_data := 'OLD: ' || :OLD.ID || ', ' || :OLD.NAME || ', ' || :OLD.VALUE;
    END IF;
    INSERT INTO "AUDIT" VALUES (SYSDATE, v_op, 'TRG_BEFORE_ROW', v_data);
END;
/

