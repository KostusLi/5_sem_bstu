CREATE TABLE T_A (
    ID_A NUMBER PRIMARY KEY,
    NAME_A VARCHAR2(50)
);

CREATE TABLE T_B (
    ID_B NUMBER PRIMARY KEY,
    ID_A NUMBER,
    VAL_B VARCHAR2(50),
    CONSTRAINT fk_A FOREIGN KEY (ID_A) REFERENCES T_A(ID_A)
);

INSERT INTO T_A (ID_A, NAME_A) VALUES (1, 'Иван');
INSERT INTO T_A (ID_A, NAME_A) VALUES (2, 'Петр');
INSERT INTO T_B (ID_B, ID_A, VAL_B) VALUES (10, 1, 'Данные Ивана');
INSERT INTO T_B (ID_B, ID_A, VAL_B) VALUES (20, 2, 'Данные Петра');
COMMIT;

CREATE VIEW V1 AS
SELECT A.ID_A, A.NAME_A, B.ID_B, B.VAL_B
FROM T_A A
INNER JOIN T_B B ON A.ID_A = B.ID_A;

SELECT * FROM V1;

