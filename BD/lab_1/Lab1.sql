    ID   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name VARCHAR2(50) NOT NULL,
    Surname  VARCHAR2(50) NOT NULL,
    Gender    CHAR(2) NOT NULL,
    
    CONSTRAINT check_gender CHECK (Gender IN ('М', 'Ж'))
);

