ALTER SESSION SET CONTAINER = CLINIC_PDB;

SELECT SYS_CONTEXT('USERENV', 'CON_NAME') AS CURRENT_PDB FROM DUAL;

CREATE TABLESPACE TS_CLINIC_DATA
    DATAFILE SIZE 100M AUTOEXTEND ON NEXT 50M MAXSIZE 2G
    ONLINE;

CREATE TABLESPACE TS_CLINIC_IDX
    DATAFILE SIZE 50M AUTOEXTEND ON NEXT 25M MAXSIZE 1G
    ONLINE;

CREATE USER CLINIC_CORE IDENTIFIED BY "ClinicCore2026!"
    DEFAULT TABLESPACE TS_CLINIC_DATA
    TEMPORARY TABLESPACE TEMP
    QUOTA UNLIMITED ON TS_CLINIC_DATA
    QUOTA UNLIMITED ON TS_CLINIC_IDX;

GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, 
      CREATE PROCEDURE, CREATE SEQUENCE, CREATE TRIGGER, 
      CREATE SYNONYM TO CLINIC_CORE;

GRANT EXECUTE ON SYS.DBMS_CRYPTO TO CLINIC_CORE;
GRANT SELECT_CATALOG_ROLE TO CLINIC_CORE;
GRANT SELECT ON V_$IM_SEGMENTS TO CLINIC_CORE;
GRANT SELECT ON V_$SQL_PLAN TO CLINIC_CORE;

CREATE OR REPLACE DIRECTORY DIR_CLINIC_JSON AS '/tmp';
GRANT READ, WRITE ON DIRECTORY DIR_CLINIC_JSON TO CLINIC_CORE;

ALTER SESSION SET CONTAINER = CLINIC_PDB;

GRANT RESTRICTED SESSION TO CLINIC_CORE;

ALTER SYSTEM DISABLE RESTRICTED SESSION;

ALTER SESSION SET CONTAINER = FREEPDB1;