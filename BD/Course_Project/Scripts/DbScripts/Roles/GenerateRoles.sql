-- 1. Переключаемся в нашу базу CLINIC_PDB
ALTER SESSION SET CONTAINER = CLINIC_PDB;

-- 2. Создаем 3 роли СУБД согласно заданию
CREATE ROLE RL_CLINIC_ADMIN;
CREATE ROLE RL_CLINIC_DOCTOR;
CREATE ROLE RL_CLINIC_REGISTRAR;

-- 3. Выдаем права на пакеты процедур (и НИКАКИХ прав на сами таблицы!)
-- Общий пакет доступен всем трём ролям:
GRANT EXECUTE ON CLINIC_CORE.PKG_COMMON TO RL_CLINIC_ADMIN;
GRANT EXECUTE ON CLINIC_CORE.PKG_COMMON TO RL_CLINIC_DOCTOR;
GRANT EXECUTE ON CLINIC_CORE.PKG_COMMON TO RL_CLINIC_REGISTRAR;

-- Пакет администратора и пакет импорта/экспорта JSON — только Главному администратору:
GRANT EXECUTE ON CLINIC_CORE.PKG_ADMIN   TO RL_CLINIC_ADMIN;
GRANT EXECUTE ON CLINIC_CORE.PKG_JSON_IO TO RL_CLINIC_ADMIN;

-- Пакет врача — только Врачу:
GRANT EXECUTE ON CLINIC_CORE.PKG_DOCTOR  TO RL_CLINIC_DOCTOR;

-- Пакет регистратора — только Регистратору:
GRANT EXECUTE ON CLINIC_CORE.PKG_REGISTRAR TO RL_CLINIC_REGISTRAR;

-- 4. Создаем публичные синонимы для пакетов, чтобы вызывать их без префикса CLINIC_CORE.
CREATE OR REPLACE PUBLIC SYNONYM PKG_COMMON    FOR CLINIC_CORE.PKG_COMMON;
CREATE OR REPLACE PUBLIC SYNONYM PKG_ADMIN     FOR CLINIC_CORE.PKG_ADMIN;
CREATE OR REPLACE PUBLIC SYNONYM PKG_DOCTOR    FOR CLINIC_CORE.PKG_DOCTOR;
CREATE OR REPLACE PUBLIC SYNONYM PKG_REGISTRAR FOR CLINIC_CORE.PKG_REGISTRAR;
CREATE OR REPLACE PUBLIC SYNONYM PKG_JSON_IO   FOR CLINIC_CORE.PKG_JSON_IO;

-- 5. Создаем пользователей БД для подключения по ролям (включая RESTRICTED SESSION для нашей PDB)
CREATE USER USR_ADMIN IDENTIFIED BY "AdminRole2026!";
GRANT CREATE SESSION, RESTRICTED SESSION, RL_CLINIC_ADMIN TO USR_ADMIN;

CREATE USER USR_DOCTOR IDENTIFIED BY "DoctorRole2026!";
GRANT CREATE SESSION, RESTRICTED SESSION, RL_CLINIC_DOCTOR TO USR_DOCTOR;

CREATE USER USR_REGISTRAR IDENTIFIED BY "RegistrarRole2026!";
GRANT CREATE SESSION, RESTRICTED SESSION, RL_CLINIC_REGISTRAR TO USR_REGISTRAR;

-- 6. Возвращаем твою вкладку SYS обратно в FREEPDB1 для твоих лабораторных
ALTER SESSION SET CONTAINER = FREEPDB1;