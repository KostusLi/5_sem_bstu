SELECT 
    (SELECT BANNER FROM V$VERSION WHERE ROWNUM = 1) AS DB_VERSION,
    SYS_CONTEXT('USERENV', 'CON_NAME') AS CURRENT_CONTAINER,
    SYS_CONTEXT('USERENV', 'CURRENT_USER') AS CURRENT_USER
FROM DUAL;

SELECT NAME, VALUE/1024/1024 AS SIZE_MB 
FROM V$PARAMETER 
WHERE NAME IN ('sga_target', 'sga_max_size', 'inmemory_size', 'pga_aggregate_target');